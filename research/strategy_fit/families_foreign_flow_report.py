"""Markdown rendering for strategy_fit/families_foreign_flow.py (plan 22 development run). Every number comes
from the results dict that module produces."""
from __future__ import annotations

from strategy_fit.h2_report import f, table

SIGNALS = ("S1", "S2")
HOLDS = (1, 3, 5)


def _row(name, k, r) -> list:
    m = r["metrics"]
    if not m["n"]:
        return [name, k, 0, 0, *["-"] * 12, r["status"]]
    g9 = r["g9"]
    v = r.get("verdict", r["status"]) + (" (" + ",".join(r["failed_gates"]) + ")" if r.get("failed_gates") else "")
    return [name, k, m["n"], m["reviews"], f(m["gross"]), f(m["null"]), f(m["edge"]), f(m["t"], 2),
            f(m["net_edge_cur"]), f(m["net_edge_cand_latest"]), f(m["net_edge_1lot"]), f(m["drop5_net_edge_cur"]),
            f(m["net_minus_ihsg"]),
            f"{f(g9['edge'])}/{f(g9['net'])}/{f(g9['net_minus_ihsg'])}", f(r["p_holm"], 3) if "p_holm" in r else "-", v]


HEADER = ["signal", "k", "trades", "dates", "gross", "null", "edge", "t (date-clust.)", "net cur", "net cand",
          "net 1-lot", "drop-5-dates net", "net-IHSG", "G9 edge/net/net-IHSG", "Holm p", "verdict"]


def exclusion_rows(out) -> list[list]:
    rows = []
    for s in SIGNALS:
        for k in HOLDS:
            ex = out["cells"][s][k]["exclusions"]
            rows.append([s, k, ex["signals"], ex["entry_not_traded"], ex["bad_bars_or_missing"], ex["not_eligible"],
                         ex["locked_upper_limit"], ex["sequential_overlap"], ex["trades"]])
    return rows


def g8_rows(out) -> list[list]:
    rows = []
    for s in SIGNALS:
        for k in HOLDS:
            g = out["cells"][s][k].get("regime_g8")
            if not g:
                continue
            cells = []
            for key in ("below_sma200", "at_or_above_sma200"):
                x = g[key]
                cells.append("-" if not x["n"] else
                             f"n={x['n']}, dates={x['reviews']}: edge {f(x['edge'])} (t {f(x['t'], 2)}), "
                             f"net {f(x['net_edge_cur'])}, net-IHSG {f(x['net_minus_ihsg'])}")
            rows.append([s, k, *cells, g["unknown_regime"]])
    return rows


def render(out) -> str:
    P = ["# Plan 22 foreign-selling rebound, DEVELOPMENT window (signals 2017-01-01..2022-12-31)\n",
         "Generated by `research/strategy_fit/families_foreign_flow.py`. Holdout NOT run. bps unless stated. Entry "
         "`open_{t+1}` (harness `next_open`: open_{t+1} -> open_{t+1+k}), sequential, locked entries skipped. net = "
         "edge - cost (current coeffs, Rp 3M); `net cand` = 2026-10-14 candidate coeffs; `net 1-lot` = 1 lot. "
         "drop-5-dates = mean net after removing the 5 best signal dates. net-IHSG = gross - cost - IHSG over the same "
         "window. t clustered by signal date.\n"]
    P += ["## Results (6 cells)\n", table(HEADER, [_row(s, k, out["cells"][s][k]) for s in SIGNALS for k in HOLDS]) + "\n"]
    P += ["## Signals before the harness\n", "```", *[f"{k}: {v}" for k, v in out["signal_diag"].items()], "```\n"]
    P += ["## Candidate drops per cell\n",
          table(["signal", "k", "signals", "entry not traded", "bad bars/missing", "not eligible", "locked upper limit",
                 "sequential overlap", "trades"], exclusion_rows(out)) + "\n"]
    P += ["## Gate matrix\n"]
    rows = []
    for s in SIGNALS:
        for k in HOLDS:
            r = out["cells"][s][k]
            if r["status"] != "tested":
                rows.append([s, k, r["status"], *["-"] * 8])
                continue
            g = r["gates"]
            mk = lambda b: "pass" if b else "FAIL"  # noqa: E731
            rows.append([s, k, "met", *[mk(g[x]) for x in ("G2", "G3a_current", "G3b_candidate", "G3c_1lot", "G4",
                                                            "G6", "G7", "G9")]])
    P += [table(["signal", "k", "sample floor", "G2", "G3a", "G3b", "G3c", "G4", "G6", "G7", "G9"], rows) + "\n"]
    P += ["## Reported only: C1 (heavy foreign BUYING, 95th pct), entry open_{t+1}\n",
          "C1a = F only; C1b = F and return >= +2%.\n",
          table(HEADER, [_row(v, k, out["c1"][v][k]) for v in out["c1"] for k in HOLDS]) + "\n"]
    P += ["## Reported only: close_{t+1} entry sensitivity\n",
          table(HEADER[:-3] + ["verdict"], [
              [*_row(s, k, out["cells"][s][k]["sens_close_entry"] | {"status": "sens"})[:-3],
               "-"] for s in SIGNALS for k in HOLDS]) + "\n"]
    P += ["## G8 regime split (IHSG vs its 200-session SMA on t; not blocking)\n",
          table(["signal", "k", "below SMA200", "at/above SMA200", "unknown"], g8_rows(out)) + "\n"]
    P += [f"## Decision rule (plan section 5)\n\n**{out['decision']['branch']}** {out['decision']['cells']}\n"]
    return "\n".join(P)
