"""Markdown rendering for strategy_fit/families_indicator_rules.py (plan 24 development run). Every number comes
from the results dict that module produces."""
from __future__ import annotations

from strategy_fit.h2_report import f, table

RULES = ("R1", "R2", "R3", "R4", "R5")
NAMES = {"R1": "golden cross 50/200", "R2": "MACD 12/26/9", "R3": "RSI14 < 30", "R4": "Bollinger 20/2",
         "R5": "RSI2 pullback"}
HEADER = ["rule", "trades", "months", "mean hold", "gross", "null", "edge", "t (month-clust.)", "Holm p",
          "cost cur", "cost cand", "cost 1-lot", "net cur", "net cand", "net 1-lot", "drop-5-dates net",
          "net-IHSG", "G9 edge/net/net-IHSG", "verdict"]


def _row(rule, r) -> list:
    m = r["metrics"]
    if not m["n"]:
        return [rule, 0, 0, *["-"] * 16, r["status"]]
    g9 = r["g9"]
    v = r["verdict"] + (" (" + ",".join(r["failed_gates"]) + ")" if r.get("failed_gates") else "")
    return [rule, m["n"], m["reviews"], f(r["hold"]["mean_hold"]), f(m["gross"]), f(m["null"]), f(m["edge"]),
            f(m["t"], 2), f(r["p_holm"], 3), f(m["cost_cur"]), f(m["cost_cand_latest"]), f(m["cost_1lot"]),
            f(m["net_edge_cur"]), f(m["net_edge_cand_latest"]), f(m["net_edge_1lot"]), f(m["drop5_net_edge_cur"]),
            f(m["net_minus_ihsg"]), f"{f(g9['edge'])}/{f(g9['net'])}/{f(g9['net_minus_ihsg'])}", v]


def _gate_rows(out) -> list[list]:
    rows = []
    for rule in RULES:
        r = out["cells"][rule]
        if r["status"] != "tested":
            rows.append([rule, r["status"], *["-"] * 8])
            continue
        g = r["gates"]
        rows.append([rule, "met", *["pass" if g[x] else "FAIL" for x in
                                    ("G2", "G3a_current", "G3b_candidate", "G3c_1lot", "G4", "G6", "G7", "G9")]])
    return rows


def _diag_rows(out) -> list[list]:
    keys = ("signals", "overlap_ignored", "not_eligible", "locked_upper_limit", "entry_not_traded", "zero_hold",
            "bad_bar_void", "no_null", "trades", "exit_signal", "exit_time_stop", "closed_at_dev_end")
    return [[rule, *[out["cells"][rule]["diag"].get(k, 0) for k in keys]] for rule in RULES], keys


def _hold_rows(out) -> list[list]:
    rows = []
    for rule in RULES:
        h = out["cells"][rule]["hold"]
        if h:
            p = out["cells"][rule]["portfolio"]
            rows.append([rule, f(h["mean_hold"]), f(h["median_hold"]), f(100 * p["time_in_market"], 1) + "%",
                         f(p["mean_open_positions_when_invested"]), f(100 * h["win_rate_gross"], 1) + "%",
                         f(100 * h["win_rate_net"], 1) + "%", f(h["net_gross_basis"]),
                         f(h["drop5_net_gross_basis"])])
    return rows


def _crand_rows(out) -> list[list]:
    rows = []
    for rule in RULES:
        c = out["cells"][rule].get("c_rand")
        if c:
            rows.append([rule, c["n_used"], f(c["rule_mean_gross_bps"]), f(c.get("rand_mean_bps")),
                         f(c.get("rand_p05_bps")), f(c.get("rand_p95_bps")), f(c["percentile"], 1)])
    return rows


def _pct(x) -> str:
    return f(100 * x, 1) + "%"


def _portfolio_rows(out) -> list[list]:
    rows = []
    for rule in RULES:
        p = out["cells"][rule].get("portfolio")
        if not p:
            continue
        for label, key in ((f"{rule} book", "rule"), ("EW eligible universe", "universe_ew"), ("IHSG", "ihsg")):
            x = p[key]
            rows.append([label, _pct(x["cagr"]), _pct(x["max_drawdown"]), f"{_pct(x['worst_year'])} ({x['worst_year_label']})"])
    return rows


def _g8_rows(out) -> list[list]:
    rows = []
    for rule in RULES:
        g = out["cells"][rule].get("regime_g8")
        if not g:
            continue
        cells = []
        for key in ("below_sma200", "at_or_above_sma200"):
            x = g[key]
            cells.append("-" if not x["n"] else
                         f"n={x['n']}, months={x['reviews']}: edge {f(x['edge'])} (t {f(x['t'], 2)}), "
                         f"net {f(x['net_edge_cur'])}, net-IHSG {f(x['net_minus_ihsg'])}")
        rows.append([rule, *cells, g["unknown_regime"]])
    return rows


def render(out) -> str:
    drows, dkeys = _diag_rows(out)
    P = ["# Plan 24 classic indicator rules, DEVELOPMENT window (entries 2015-01-01..2022-12-31)\n",
         "Generated by `research/strategy_fit/families_indicator_rules.py`. Holdout NOT run. bps unless stated. Entry "
         "`open_{t+1}`, exit `open_{u+1}` after the first exit signal / time stop; trades open at the last development "
         f"session ({out['last_dev_session']}) are closed at its open. null = hold x the same name's mean daily open-to-open "
         "total return over eligible sessions of the entry year. net = edge - cost (current coeffs, Rp 3M); `cand` = "
         "2026-10-14 candidate coeffs; `1-lot` = 1 lot. drop-5-dates = mean net after removing the 5 best entry dates. "
         "net-IHSG = gross - cost - IHSG over the same open->open window. t clustered by entry calendar month.\n"]
    P += ["## Results (5 cells)\n", table(HEADER, [_row(r, out["cells"][r]) for r in RULES]) + "\n"]
    P += ["## Gate matrix\n", table(["rule", "sample floor", "G2", "G3a", "G3b", "G3c", "G4", "G6", "G7", "G9"],
                                    _gate_rows(out)) + "\n"]
    P += ["## Candidate drops per rule\n", table(["rule", *dkeys], drows) + "\n"]
    P += ["## Reported only: holds, time in market, win rate, gross-basis net\n",
          table(["rule", "mean hold", "median hold", "time in market", "mean open positions (when invested)",
                 "win rate gross", "win rate net", "mean gross - cost", "drop-5 gross - cost"], _hold_rows(out)) + "\n"]
    P += ["## Reported only: C-rand control (200 draws, seed 24)\n",
          table(["rule", "trades used", "rule mean gross", "random mean", "random p05", "random p95",
                 "percentile of rule"], _crand_rows(out)) + "\n"]
    P += ["## Reported only: portfolio view (equal weight across open positions, net of cost)\n",
          table(["series", "CAGR", "max drawdown", "worst year"], _portfolio_rows(out)) + "\n"]
    P += ["## G8 regime split (IHSG vs its 200-session SMA on the signal day; not blocking)\n",
          table(["rule", "below SMA200", "at/above SMA200", "unknown"], _g8_rows(out)) + "\n"]
    P += [f"## Decision rule (plan section 5)\n\n**{out['decision']['branch']}** {out['decision']['cells']}\n"]
    return "\n".join(P)
